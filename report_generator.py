def generate_html_report(findings, target_path, output_path):
    findings = sort_findings(findings)
    counts = _summary_counts(findings)

    cards = ""
    for sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"):
        color = Severity[sev].color
        cards += (f'<div class="card"><div class="num" style="color:{color}">'
                   f'{counts[sev]}</div><div class="label">{sev}</div></div>')
    cards += (f'<div class="card"><div class="num">{len(findings)}</div>'
              f'<div class="label">Total</div></div>')

    if findings:
        rows = ""
        for f in findings:
            rows += (
                "<tr>"
                f'<td class="file">{_esc(f.file)}:{f.line}</td>'
                f'<td>{_esc(f.vulnerability)}</td>'
                f'<td><span class="sev" style="background:{f.severity.color}">'
                f'{f.severity}</span></td>'
                f'<td>{_esc(f.description)}</td>'
                f'<td>{_esc(f.recommendation)}</td>'
                f'<td><code>{_esc(f.code_snippet)}</code></td>'
                f'<td>{_esc(f.source)}</td>'
                "</tr>"
            )
        table = (
            "<table><thead><tr>"
            "<th>Location</th><th>Vulnerability</th><th>Severity</th>"
            "<th>Description</th><th>Recommendation</th><th>Code</th><th>Engine</th>"
            "</tr></thead><tbody>" + rows + "</tbody></table>"
        )
    else:
        table = '<div class="empty">No issues found. 🎉</div>'

    practices = "".join(f"<li>{_esc(p)}</li>" for p in BEST_PRACTICES)

    html = _HTML_TEMPLATE.format(
        target=_esc(target_path),
        generated_at=datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        summary_cards=cards,
        table_or_empty=table,
        practices=practices,
    )
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)
    return output_path


def _esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


# --------------------------------------------------------------------------
# PDF (reportlab)
# --------------------------------------------------------------------------
def generate_pdf_report(findings, target_path, output_path):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                     Table, TableStyle, ListFlowable, ListItem)

    findings = sort_findings(findings)
    counts = _summary_counts(findings)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleX", parent=styles["Title"], fontSize=20)
    h2_style = ParagraphStyle("H2X", parent=styles["Heading2"], spaceBefore=14)
    body = ParagraphStyle("BodyX", parent=styles["BodyText"], fontSize=8, leading=10)
    cell = ParagraphStyle("CellX", parent=styles["BodyText"], fontSize=7.5, leading=9)

    doc = SimpleDocTemplate(output_path, pagesize=A4,
                             topMargin=18 * mm, bottomMargin=16 * mm,
                             leftMargin=14 * mm, rightMargin=14 * mm)
    story = []
    story.append(Paragraph("PySecure Auditor Report", title_style))
    story.append(Paragraph(
        f"Target: {_esc(target_path)}<br/>"
        f"Generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        body))
    story.append(Spacer(1, 10))

    sum_data = [["Critical", "High", "Medium", "Low", "Info", "Total"],
                [counts["CRITICAL"], counts["HIGH"], counts["MEDIUM"],
                 counts["LOW"], counts["INFO"], len(findings)]]
    sum_table = Table(sum_data, hAlign="LEFT")
    sum_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1d212b")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(sum_table)
    story.append(Spacer(1, 16))

    if findings:
        story.append(Paragraph("Findings", h2_style))
        table_data = [["Location", "Vulnerability", "Sev", "Description",
                        "Recommendation"]]
        for f in findings:
            table_data.append([
                Paragraph(_esc(f"{os.path.basename(f.file)}:{f.line}"), cell),
                Paragraph(_esc(f.vulnerability), cell),
                Paragraph(str(f.severity), cell),
                Paragraph(_esc(f.description), cell),
                Paragraph(_esc(f.recommendation), cell),
            ])
        t = Table(table_data, colWidths=[55, 90, 32, 150, 150], repeatRows=1)
        style_cmds = [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1d212b")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#dddddd")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]
        for i, f in enumerate(findings, start=1):
            style_cmds.append(("BACKGROUND", (2, i), (2, i),
                                colors.HexColor(f.severity.color)))
            style_cmds.append(("TEXTCOLOR", (2, i), (2, i), colors.white))
        t.setStyle(TableStyle(style_cmds))
        story.append(t)
    else:
        story.append(Paragraph("No issues found.", body))

    story.append(Spacer(1, 18))
    story.append(Paragraph("Recommended Best Practices", h2_style))
    story.append(ListFlowable(
        [ListItem(Paragraph(_esc(p), body)) for p in BEST_PRACTICES],
        bulletType="bullet"))

    doc.build(story)
    return output_path
