"""
report_generator.py
Turns a list of Finding objects into JSON, HTML, or PDF reports.
"""

import datetime
import json
import os
from collections import Counter

from utils import Severity, sort_findings

BEST_PRACTICES = [
    "Validate and sanitize all user input.",
    "Store secrets in environment variables or a secrets manager, never in code.",
    "Avoid eval() and exec(); prefer safe parsers (ast.literal_eval, json).",
    "Use parameterized queries for all database access.",
    "Hash passwords with bcrypt, scrypt, or Argon2 - never MD5/SHA-1.",
    "Use the 'secrets' module for security-sensitive randomness, not 'random'.",
    "Keep third-party dependencies updated and monitor for known CVEs.",
    "Apply the Principle of Least Privilege to services, files, and DB users.",
    "Handle exceptions securely without leaking stack traces or secrets to users.",
    "Never run production services with debug mode enabled.",
]


def _summary_counts(findings):
    counts = Counter(str(f.severity) for f in findings)
    for s in ("CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"):
        counts.setdefault(s, 0)
    return counts


# --------------------------------------------------------------------------
# JSON
# --------------------------------------------------------------------------
def generate_json_report(findings, target_path, output_path, meta=None):
    findings = sort_findings(findings)
    counts = _summary_counts(findings)
    report = {
        "tool": "PySecure Auditor",
        "target": target_path,
        "generated_at": datetime.datetime.now().isoformat(timespec="seconds"),
        "summary": {
            "total_findings": len(findings),
            "by_severity": dict(counts),
        },
        "meta": meta or {},
        "findings": [f.to_dict() for f in findings],
        "best_practices": BEST_PRACTICES,
    }
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    return output_path


